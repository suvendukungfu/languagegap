"""Pydantic schemas for Benchmark Integrity, Provenance Manifest, and Reproducibility Passport."""

from __future__ import annotations

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.schemas.evaluation import DimensionScores


class BenchmarkIntegrityReport(BaseModel):
    """Structured report returned by the benchmark integrity validator."""
    valid: bool = Field(..., description="True if benchmark passes all structural and linguistic integrity checks")
    errors: List[str] = Field(default_factory=list, description="Fatal integrity violations")
    warnings: List[str] = Field(default_factory=list, description="Non-fatal warnings or provenance advisories")
    benchmark_id: str = Field(..., description="Canonical dataset identifier")
    benchmark_version: str = Field(..., description="SemVer dataset version")
    task_count: int = Field(..., description="Number of canonical tasks in the benchmark")
    language_coverage: Dict[str, int] = Field(..., description="Task count breakdown per language")
    expected_languages: List[str] = Field(default_factory=lambda: ["en", "hi", "pa", "or"])
    benchmark_sha256: str = Field(..., description="SHA-256 hex digest of the raw benchmark bytes")
    verified_at: str = Field(..., description="ISO 8601 timestamp of validation execution")


class ReviewerOverrideMetadata(BaseModel):
    """Audit trail record for human score corrections."""
    response_id: str
    task_id: str
    language: str
    reviewer_id: str
    reviewed_at: str
    original_scores: DimensionScores
    overridden_scores: DimensionScores
    reviewer_notes: str


class EvaluationPassportResponse(BaseModel):
    """Machine-readable reproducibility passport and provenance manifest."""
    evaluation_run_id: str = Field(..., description="Unique UUID of the evaluation run")
    benchmark_id: str = Field(..., description="Benchmark dataset evaluated")
    benchmark_version: str = Field(..., description="Benchmark dataset version")
    benchmark_sha256: str = Field(..., description="SHA-256 hash of the exact benchmark data")
    provider_id: str = Field(..., description="Configured inference provider (mock, gemma, etc.)")
    actual_model_id: str = Field(..., description="Actual model identifier used during inference")
    is_mock_provider: bool = Field(..., description="Explicitly True if output was generated by deterministic mock")
    evaluation_timestamp: str = Field(..., description="ISO 8601 timestamp when run was initialized")
    completed_at: Optional[str] = Field(default=None, description="ISO 8601 timestamp when run completed")
    execution_status: str = Field(..., description="Run state: pending, running, completed, failed")
    language_set: List[str] = Field(..., description="List of languages evaluated in this run")
    task_count: int = Field(..., description="Number of distinct paired tasks evaluated")
    sample_count: int = Field(..., description="Total individual model responses recorded")
    scoring_configuration: Dict[str, Any] = Field(..., description="Rubric dimension definitions and sampling parameters")
    evaluator_version: str = Field(default="1.0.0", description="Evaluation engine algorithm version")
    language_wise_scores: Dict[str, Dict[str, float]] = Field(..., description="Mean score breakdown per dimension by language")
    language_means: Dict[str, float] = Field(..., description="Composite mean score (0-14) per language")
    dimension_wise_scores: Dict[str, float] = Field(..., description="Mean score per dimension across all languages")
    parity_gap: float = Field(..., description="Cross-lingual parity gap (max language mean - min language mean)")
    highest_language: str = Field(..., description="Language code with highest aggregate performance")
    lowest_language: str = Field(..., description="Language code with lowest aggregate performance")
    human_review_status: str = Field(..., description="unreviewed, partially_reviewed, or fully_reviewed")
    human_review_count: int = Field(..., description="Number of responses verified by human reviewers")
    reviewer_overrides: List[ReviewerOverrideMetadata] = Field(default_factory=list, description="Audit trail of human reviewer overrides")
    benchmark_integrity: BenchmarkIntegrityReport = Field(..., description="Embedded integrity validation of the benchmark used")
    exported_at: str = Field(..., description="ISO 8601 timestamp when passport was generated")
